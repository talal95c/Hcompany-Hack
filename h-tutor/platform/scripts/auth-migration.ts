// Writes the SQL for better-auth's tables (users, sessions, organizations,
// members, invitations) into migrations/0001_auth.sql, computed by better-auth
// itself against an empty in-memory SQLite: `npm run migration:auth`.
import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.ts";

const { compileMigrations } = await getMigrations(authOptions(new DatabaseSync(":memory:"), { BETTER_AUTH_SECRET: "x".repeat(32) }));
const sql = await compileMigrations();
const out = fileURLToPath(new URL("../migrations/0001_auth.sql", import.meta.url));
writeFileSync(out, `-- Generated by scripts/auth-migration.ts from better-auth's schema. Do not edit.\n${sql}\n`);
console.log(sql);
